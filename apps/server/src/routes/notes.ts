// Batch reorder (folders + notes)
noteRoutes.put('/:campaignId/notes/reorder', async (c) => {
  const campaignId = c.req.param('campaignId');
  const user = c.get('user') as AuthUser;
  const body = await c.req.json<ReorderNotesInput>();

  if (!body.items?.length) return c.json({ error: 'No items to reorder' }, 400);

  const stmts: D1PreparedStatement[] = [];

  for (const item of body.items) {
    if (item.folderId !== undefined) {
      // This is a note being reordered/moved
      stmts.push(
        c.env.DB.prepare(
          "UPDATE notes SET sort_order = ?, folder_id = ?, updated_at = datetime('now') WHERE id = ? AND campaign_id = ? AND user_id = ?",
        ).bind(item.sortOrder, item.folderId, item.id, campaignId, user.id),
      );
    } else if (item.parentFolderId !== undefined) {
      // This is a folder being reordered/moved
      stmts.push(
        c.env.DB.prepare(
          "UPDATE note_folders SET sort_order = ?, parent_folder_id = ?, updated_at = datetime('now') WHERE id = ? AND campaign_id = ? AND user_id = ?",
        ).bind(item.sortOrder, item.parentFolderId, item.id, campaignId, user.id),
      );
    } else {
      // Just reorder (sort_order only)
      // Try notes first, then folders
      stmts.push(
        c.env.DB.prepare(
          "UPDATE notes SET sort_order = ?, updated_at = datetime('now') WHERE id = ? AND campaign_id = ? AND user_id = ?",
        ).bind(item.sortOrder, item.id, campaignId, user.id),
      );
      stmts.push(
        c.env.DB.prepare(
          "UPDATE note_folders SET sort_order = ?, updated_at = datetime('now') WHERE id = ? AND campaign_id = ? AND user_id = ?",
        ).bind(item.sortOrder, item.id, campaignId, user.id),
      );
    }
  }

  await c.env.DB.batch(stmts);
  return c.json({ ok: true });
});
