// Search notes
noteRoutes.get('/:campaignId/notes/search', async (c) => {
  const campaignId = c.req.param('campaignId');
  const user = c.get('user') as AuthUser;
  const q = c.req.query('q');
  const scope = await resolveScope(c, campaignId, user, c.req.query('scope'));
  if (isResponse(scope)) return scope;

  if (!q?.trim()) return c.json({ notes: [] });

  const term = `%${q.trim()}%`;
  const results = await c.env.DB.prepare(
    'SELECT * FROM notes WHERE campaign_id = ? AND user_id = ? AND scope = ? AND (title LIKE ? OR content LIKE ?) ORDER BY updated_at DESC',
  )
    .bind(campaignId, user.id, scope, term, term)
    .all<NoteRow>();

  return c.json({ notes: results.results.map(rowToNote) });
});

// Create note
noteRoutes.post('/:campaignId/notes', async (c) => {
  const campaignId = c.req.param('campaignId');
  const user = c.get('user') as AuthUser;
  const body = await c.req.json<CreateNoteInput>();
  const scope = await resolveScope(c, campaignId, user, body.scope ?? c.req.query('scope'));
  if (isResponse(scope)) return scope;

  if (!body.title?.trim()) return c.json({ error: 'Title is required' }, 400);
  if (!body.folderId) return c.json({ error: 'Folder is required' }, 400);

  // Verify folder belongs to this user+campaign
  const folder = await c.env.DB.prepare(
    'SELECT id FROM note_folders WHERE id = ? AND campaign_id = ? AND user_id = ? AND scope = ?',
  )
    .bind(body.folderId, campaignId, user.id, scope)
    .first();
  if (!folder) return c.json({ error: 'Folder not found' }, 404);

  // Get the next sort order
  const maxOrder = await c.env.DB.prepare(
    'SELECT MAX(sort_order) as max_order FROM notes WHERE folder_id = ?',
  )
    .bind(body.folderId)
    .first<{ max_order: number | null }>();

  const id = crypto.randomUUID();
  const sortOrder = (maxOrder?.max_order ?? -1) + 1;

  await c.env.DB.prepare(
    'INSERT INTO notes (id, campaign_id, user_id, scope, folder_id, title, content, sort_order) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
  )
    .bind(id, campaignId, user.id, scope, body.folderId, body.title.trim(), body.content ?? '', sortOrder)
    .run();

  const row = await c.env.DB.prepare('SELECT * FROM notes WHERE id = ?').bind(id).first<NoteRow>();
  if (!row) return c.json({ error: 'Failed to create note' }, 500);

  return c.json({ note: rowToNote(row) }, 201);
});

