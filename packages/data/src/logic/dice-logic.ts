/**
 * Dice Logic
 *
 * Pure functions for dice rolling and result creation.
 * Supports local rolling (client-side), manual entry (physical dice),
 * and integration with server-authoritative rolls.
 *
 * @example
 * import { DiceLogic } from '@anvil/data';
 *
 * // Roll 2d10 for a power roll
 * const result = DiceLogic.powerRoll(3); // +3 modifier
 * console.log(result.finalTotal, result.tier);
 *
 * // Manual entry from physical dice
 * const manualResult = DiceLogic.manualResult(14);
 * console.log(manualResult.tier); // 2
 *
 * // Roll arbitrary notation
 * const damageRoll = DiceLogic.rollNotation('2d6+3');
 */

import * as RollLogic from './roll-logic.js';

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

/**
 * How the roll was generated.
 * - 'local': Generated by DiceLogic (client-side random)
 * - 'manual': Entered by Director (physical dice)
 * - 'server': From server-authoritative system
 */
export type DiceRollSource = 'local' | 'manual' | 'server';

/**
 * Result of a dice roll.
 */
export interface DiceRollResult {
  /** Dice notation that was rolled (e.g., "2d10", "1d6+3") */
  notation: string;
  /** Individual die results (empty for manual entry) */
  rolls: number[];
  /** Sum of dice only */
  total: number;
  /** Modifier applied to roll */
  modifier: number;
  /** Final result (total + modifier) */
  finalTotal: number;
  /** Tier for power rolls (undefined for non-power rolls) */
  tier?: 1 | 2 | 3;
  /** How this roll was generated */
  source: DiceRollSource;
}

/**
 * Parsed dice notation.
 */
export interface ParsedNotation {
  /** Number of dice to roll */
  count: number;
  /** Number of sides per die */
  sides: number;
  /** Modifier to add/subtract */
  modifier: number;
}

// ---------------------------------------------------------------------------
// Random Number Generation
// ---------------------------------------------------------------------------

/**
 * Check if Web Crypto API is available.
 */
function hasCrypto(): boolean {
  return (
    typeof globalThis !== 'undefined' &&
    globalThis.crypto !== undefined &&
    typeof globalThis.crypto.getRandomValues === 'function'
  );
}

/**
 * Generate a cryptographically secure random integer in range [min, max].
 * Falls back to Math.random if crypto is unavailable.
 */
function secureRandomInt(min: number, max: number): number {
  const range = max - min + 1;

  if (hasCrypto()) {
    // Use rejection sampling for unbiased results
    const bytesNeeded = Math.ceil(Math.log2(range) / 8) || 1;
    const maxValid = Math.floor(256 ** bytesNeeded / range) * range - 1;

    let value: number;
    const array = new Uint8Array(bytesNeeded);

    do {
      globalThis.crypto.getRandomValues(array);
      value = array.reduce((acc, byte, i) => acc + byte * 256 ** i, 0);
    } while (value > maxValid);

    return min + (value % range);
  }

  // Fallback to Math.random (less secure but works everywhere)
  return min + Math.floor(Math.random() * range);
}

