// Core Rolling Functions
// ---------------------------------------------------------------------------

/**
 * Roll a single die.
 *
 * @param sides - Number of sides on the die (e.g., 6 for d6, 10 for d10)
 * @returns Random value from 1 to sides inclusive
 *
 * @example
 * const d6 = DiceLogic.rollDie(6);  // 1-6
 * const d10 = DiceLogic.rollDie(10); // 1-10
 */
export function rollDie(sides: number): number {
  if (sides < 1 || !Number.isInteger(sides)) {
    throw new Error(`DiceLogic.rollDie: sides must be a positive integer, got ${sides}`);
  }
  return secureRandomInt(1, sides);
}

/**
 * Roll multiple dice of the same type.
 *
 * @param count - Number of dice to roll
 * @param sides - Number of sides per die
 * @returns Array of individual die results
 *
 * @example
 * const dice = DiceLogic.rollDice(2, 10); // Roll 2d10
 * const sum = dice.reduce((a, b) => a + b, 0);
 */
export function rollDice(count: number, sides: number): number[] {
  if (count < 1 || !Number.isInteger(count)) {
    throw new Error(`DiceLogic.rollDice: count must be a positive integer, got ${count}`);
  }
  return Array.from({ length: count }, () => rollDie(sides));
}

// ---------------------------------------------------------------------------
// Power Roll (2d10)
// ---------------------------------------------------------------------------

/**
 * Execute a Draw Steel power roll (2d10 + modifier).
 * Automatically calculates tier.
 *
 * @param modifier - Value to add to the roll (characteristic value, bonuses)
 * @returns Complete roll result with tier
 *
 * @example
 * // Basic power roll
 * const result = DiceLogic.powerRoll();
 *
 * // With +3 Might modifier
 * const mightRoll = DiceLogic.powerRoll(3);
 * console.log(mightRoll.tier); // 1, 2, or 3
 */
export function powerRoll(modifier: number = 0): DiceRollResult {
  const rolls = rollDice(2, 10);
  const total = rolls[0]! + rolls[1]!;
  const finalTotal = total + modifier;

  return {
    notation: modifier === 0 ? '2d10' : `2d10${modifier >= 0 ? '+' : ''}${modifier}`,
    rolls,
    total,
    modifier,
    finalTotal,
    tier: RollLogic.getTier(finalTotal),
    source: 'local',
  };
}

