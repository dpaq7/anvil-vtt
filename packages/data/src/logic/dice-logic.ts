/**
 * Format a roll result for display.
 *
 * @example
 * const result = DiceLogic.powerRoll(3);
 * console.log(DiceLogic.formatResult(result));
 * // "7 + 5 + 3 = 15 (Tier 2)"
 */
export function formatResult(result: DiceRollResult): string {
  const parts: string[] = [];

  if (result.rolls.length > 0) {
    parts.push(result.rolls.join(' + '));
  } else {
    parts.push(String(result.total));
  }

  if (result.modifier !== 0) {
    parts.push(result.modifier > 0 ? `+ ${result.modifier}` : `- ${Math.abs(result.modifier)}`);
  }

  let formatted = parts.join(' ') + ` = ${result.finalTotal}`;

  if (result.tier !== undefined) {
    formatted += ` (Tier ${result.tier})`;
  }

  return formatted;
}
