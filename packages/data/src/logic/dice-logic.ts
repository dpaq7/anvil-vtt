// ---------------------------------------------------------------------------
// Notation Parsing
// ---------------------------------------------------------------------------

/**
 * Parse a dice notation string.
 *
 * @param notation - Dice notation (e.g., "2d6", "1d10+3", "3d8-2")
 * @returns Parsed components
 * @throws Error if notation is invalid
 *
 * @example
 * const { count, sides, modifier } = DiceLogic.parseNotation('2d6+3');
 * // count: 2, sides: 6, modifier: 3
 */
export function parseNotation(notation: string): ParsedNotation {
  const match = notation.match(/^(\d+)d(\d+)([+-]\d+)?$/i);
  if (!match) {
    throw new Error(
      `DiceLogic.parseNotation: Invalid notation "${notation}". Expected format like "2d6", "1d10+3", etc.`
    );
  }

  return {
    count: parseInt(match[1]!, 10),
    sides: parseInt(match[2]!, 10),
    modifier: match[3] ? parseInt(match[3], 10) : 0,
  };
}

/**
 * Roll dice from a notation string.
 *
 * @param notation - Dice notation (e.g., "2d6+3")
 * @returns Roll result
 *
 * @example
 * const damage = DiceLogic.rollNotation('2d6+3');
 * console.log(damage.finalTotal); // 5-15
 */
export function rollNotation(notation: string): DiceRollResult {
  const { count, sides, modifier } = parseNotation(notation);
  const rolls = rollDice(count, sides);
  const total = rolls.reduce((sum, r) => sum + r, 0);
  const finalTotal = total + modifier;

  // Add tier if this is a power roll (2d10)
  const isPowerRoll = count === 2 && sides === 10;

  return {
    notation,
    rolls,
    total,
    modifier,
    finalTotal,
    tier: isPowerRoll ? RollLogic.getTier(finalTotal) : undefined,
    source: 'local',
  };
}

