// Manual Entry
// ---------------------------------------------------------------------------

/**
 * Create a roll result from manual entry (for physical dice users).
 * The Director enters the total, and we create a result structure.
 *
 * @param total - The total rolled on physical dice
 * @param notation - What was supposedly rolled (default "2d10" for power rolls)
 * @returns Roll result with source: 'manual'
 *
 * @example
 * // Director rolled 14 on physical 2d10
 * const result = DiceLogic.manualResult(14);
 * console.log(result.tier); // 2
 *
 * // With modifier already applied
 * const withMod = DiceLogic.manualResult(17, '2d10+3');
 */
export function manualResult(total: number, notation: string = '2d10'): DiceRollResult {
  const { count, sides, modifier } = parseNotation(notation);
  const isPowerRoll = count === 2 && sides === 10;

  // The total provided is the finalTotal (including modifier)
  const diceTotal = total - modifier;

  return {
    notation,
    rolls: [], // Unknown individual rolls for manual entry
    total: diceTotal,
    modifier,
    finalTotal: total,
    tier: isPowerRoll ? RollLogic.getTier(total) : undefined,
    source: 'manual',
  };
}

/**
 * Create a roll result from server data.
 * Used to wrap server-authoritative roll results.
 *
 * @param dice - Individual die values from server
 * @param modifier - Modifier applied
 * @param notation - Dice notation
 * @returns Roll result with source: 'server'
 *
 * @example
 * // From server response
 * const result = DiceLogic.serverResult([7, 5], 3, '2d10+3');
 */
export function serverResult(
  dice: number[],
  modifier: number = 0,
  notation: string = '2d10'
): DiceRollResult {
  const total = dice.reduce((sum, d) => sum + d, 0);
  const finalTotal = total + modifier;

  const { count, sides } = parseNotation(notation);
  const isPowerRoll = count === 2 && sides === 10;

  return {
    notation,
    rolls: dice,
    total,
    modifier,
    finalTotal,
    tier: isPowerRoll ? RollLogic.getTier(finalTotal) : undefined,
    source: 'server',
  };
}

