// Writes tokens/look-anvil.css from tokens/anvil-tokens.json.
// Emits the Storyboard tokens as --color-*, --art-*, --shape-*, --type-*, --space-*, --layout-* and --display-*, and maps them to
// the stageshow kit's --ss-* tokens (kit/ references/looks.md).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'anvil-tokens.json'), 'utf8'));

const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
const alpha = (hex, a) => `rgb(${hexToRgb(hex)} / ${a})`;
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const lines = (o) => Object.entries(o).map(([k, val]) => `  ${k}: ${val};`).join('\n');
const group = (prefix, o) => Object.fromEntries(Object.entries(o).map(([k, val]) => [`--${prefix}-${kebab(k)}`, val]));

function theme(name) {
  const m = t.themes[name];
  const { mapDim, ...colours } = m;
  return lines({
    ...group('color', colours),
    '--map-dim': mapDim,
    '--ss-canvas': m.canvas,
    '--ss-surface': m.surface,
    '--ss-chrome': m.well,
    '--ss-well': m.well,
    '--ss-raised': m.raised,
    '--ss-line': m.line,
    '--ss-line-faint': m.lineQuiet,
    '--ss-text-strong': m.text,
    '--ss-text': m.text,
    '--ss-text-faint': m.textSoft,
    '--ss-icon': m.textSoft,
    '--ss-icon-faint': m.textSoft,
    '--ss-accent': m.active,
    '--ss-accent-2': m.active,
    '--ss-accent-soft': m.activeSoft,
    '--ss-accent-text': m.active,
    '--ss-on-accent': m.onActive,
    '--ss-success': m.success,
    '--ss-success-soft': alpha(m.success, 0.15),
    '--ss-success-text': m.success,
    '--ss-danger': m.alert,
    '--ss-danger-soft': alpha(m.alert, 0.15),
    '--ss-danger-text': m.alert,
    '--ss-warning': m.danger,
    '--ss-warning-soft': alpha(m.danger, 0.2),
    '--ss-warning-text': m.text,
  });
}

const css = `/* GENERATED by tokens/build-look.mjs from tokens/anvil-tokens.json. Do not edit by hand. */
/* Usage: <Stage className="look-anvil" theme="light"> (or "dark"). */

.look-anvil .ss-stage {
  --ss-font: ${t.fonts.body};
  --ss-font-display: ${t.fonts.display};
  --ss-mono: ${t.fonts.mono};
  --ss-radius-sm: ${t.shape.radius};
  --ss-radius-md: ${t.shape.radius};
  --ss-radius-lg: ${t.shape.radius};
  --ss-radius-window: ${t.shape.radius};
  --ss-radius-pill: 9999px;
${lines(group('font', { display: t.fonts.display, body: t.fonts.body, script: t.fonts.script }))}
${lines(group('type', t.type))}
${lines(group('type-1280', t.type1280))}
${lines(group('shape', t.shape))}
${lines(group('space', t.space))}
${lines(group('layout', t.layout))}
${lines(group('display', t.display))}
${lines(group('color-scene', t.scene))}
${lines(group('color-on-scene', t.onScene))}
${lines(group('art', t.art))}
}

.look-anvil .ss-stage[data-theme="light"] {
${theme('light')}
}

.look-anvil .ss-stage[data-theme="dark"] {
${theme('dark')}
}
`;
writeFileSync(join(here, 'look-anvil.css'), css);
console.log('wrote tokens/look-anvil.css');
