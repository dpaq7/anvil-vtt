// Writes tokens/look-anvil.css from tokens/anvil-tokens.json.
// Maps Anvil's tokens to the stageshow kit's --ss-* tokens (kit/ references/looks.md).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'anvil-tokens.json'), 'utf8'));

const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
const alpha = (hex, a) => `rgb(${hexToRgb(hex)} / ${a})`;

function theme(name) {
  const m = t.themes[name];
  const z = m.zinc;
  const dark = name === 'dark';
  const accent = dark ? t.brand.accent : t.brand.ember[500];
  const onAccent = dark ? t.brand.ink : '#ffffff';
  const lines = dark
    ? { line: alpha(z[100], 0.14), faint: alpha(z[100], 0.07) }
    : { line: alpha(z[100], 0.14), faint: alpha(z[100], 0.07) };
  const v = {
    '--ss-canvas': z[950],
    '--ss-surface': z[900],
    '--ss-chrome': z[800],
    '--ss-well': dark ? z[950] : z[800],
    '--ss-raised': dark ? z[800] : z[900],
    '--ss-line': lines.line,
    '--ss-line-faint': lines.faint,
    '--ss-text-strong': z[50],
    '--ss-text': z[200],
    '--ss-text-faint': z[500],
    '--ss-icon': z[400],
    '--ss-icon-faint': z[600],
    '--ss-accent': accent,
    '--ss-accent-2': dark ? t.brand.ember[400] : t.brand.ember[600],
    '--ss-accent-soft': alpha(accent, dark ? 0.16 : 0.12),
    '--ss-accent-text': dark ? t.brand.accent : t.brand.ember[600],
    '--ss-on-accent': onAccent,
    '--ss-success': m.success,
    '--ss-success-soft': alpha(m.success, 0.15),
    '--ss-success-text': m.success,
    '--ss-danger': m.danger,
    '--ss-danger-soft': alpha(m.danger, 0.15),
    '--ss-danger-text': m.danger,
    '--ss-warning': m.warning,
    '--ss-warning-soft': alpha(m.warning, 0.15),
    '--ss-warning-text': m.warning,
  };
  return Object.entries(v).map(([k, val]) => `  ${k}: ${val};`).join('\n');
}

const css = `/* GENERATED by tokens/build-look.mjs from tokens/anvil-tokens.json. Do not edit by hand. */
/* Usage: <Stage className="look-anvil" theme="dark"> (or "light"). */

.look-anvil .ss-stage {
  --ss-font: ${t.fonts.body};
  --ss-font-display: ${t.fonts.display};
  --ss-mono: ${t.fonts.mono};
  --ss-radius-sm: 6px;
  --ss-radius-md: 8px;
  --ss-radius-lg: 12px;
  --ss-radius-window: ${t.shape.card};
  --ss-radius-pill: ${t.shape.chip};
  --anvil-shadow-paper: ${t.shadow.paper};
  --anvil-shadow-paper-lift: ${t.shadow.paperLift};
${Object.entries(t.scene).map(([k, val]) => `  --anvil-scene-${k}: ${val};`).join('\n')}
${Object.entries(t.brand.parchment).map(([k, val]) => `  --anvil-parchment-${k}: ${val};`).join('\n')}
  --anvil-flow-director: ${t.themes.dark.flowDirector};
  --anvil-flow-player: ${t.themes.dark.flowPlayer};
  --anvil-highlight: ${t.themes.dark.highlight};
}

.look-anvil .ss-stage[data-theme="dark"] {
${theme('dark')}
}

.look-anvil .ss-stage[data-theme="light"] {
${theme('light')}
  --anvil-flow-director: ${t.themes.light.flowDirector};
  --anvil-flow-player: ${t.themes.light.flowPlayer};
  --anvil-highlight: ${t.themes.light.highlight};
}
`;
writeFileSync(join(here, 'look-anvil.css'), css);
console.log('wrote tokens/look-anvil.css');
